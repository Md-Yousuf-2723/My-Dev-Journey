# Mapping Type : Dictionary 
# - Keys must be unique
# Syntax : 
# variable = {
#     "key1": "value"
#     "key2": "value"
# }
Student = {
    "name": "Yousuf",
    "age": 23,
    "dept": "ECE"
}
# Printing all
print(Student)
# Printing specific
print(Student["name"])
print(Student["age"])
print(Student["dept"])

print(type(Student))